def make_words_from_text(text: str, page: int, base_x: float, base_y: float) -> list[Word]:
    words = []
    lines = text.strip().splitlines()
    y = base_y
    for line in lines:
        if not line.strip():
            y += 15
            continue
        line_words = line.strip().split()
        x = base_x
        for w in line_words:
            is_rtl = _text_is_rtl(w)
            raw = _fix_rtl_word_chars(w) if is_rtl else w
            norm = _normalize_word_text(raw, mirror_brackets=is_rtl)
            words.append(Word(text=norm, page=page, x0=x, top=y, x1=x+30, bottom=y+12))
            x += 35
        y += 15
    return words

